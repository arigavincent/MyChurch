export const adminCssVars = adminThemeVars.midnight;

export function getAdminCssVars(mode = 'midnight') {
  return adminThemeVars[mode] || adminThemeVars.midnight;
}

export function getAdminCssVarsText(mode = 'midnight') {
  return Object.entries(getAdminCssVars(mode))
    .map(([key, value]) => `  ${key}: ${value};`)
    .join('\n');
}
